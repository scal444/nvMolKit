#include <torch/extension.h>

void launch_fmcs_batch(torch::Tensor tier_config,
                       torch::Tensor pair_meta,
                       torch::Tensor query_row_offsets,
                       torch::Tensor query_col_indices,
                       torch::Tensor query_bond_indices,
                       torch::Tensor query_bond_endpoints,
                       torch::Tensor target_row_offsets,
                       torch::Tensor target_col_indices,
                       torch::Tensor target_bond_indices,
                       torch::Tensor target_bond_endpoints,
                       torch::Tensor atom_match_words,
                       torch::Tensor bond_match_words,
                       torch::Tensor pair_input_storage,
                       torch::Tensor queue_storage,
                       torch::Tensor scratch_storage,
                       torch::Tensor raw_result_storage,
                       torch::Tensor stats,
                       torch::Tensor atom_mapping,
                       torch::Tensor bond_mapping);

void run(torch::Tensor tier_config,
         torch::Tensor pair_meta,
         torch::Tensor query_row_offsets,
         torch::Tensor query_col_indices,
         torch::Tensor query_bond_indices,
         torch::Tensor query_bond_endpoints,
         torch::Tensor target_row_offsets,
         torch::Tensor target_col_indices,
         torch::Tensor target_bond_indices,
         torch::Tensor target_bond_endpoints,
         torch::Tensor atom_match_words,
         torch::Tensor bond_match_words,
         torch::Tensor pair_input_storage,
         torch::Tensor queue_storage,
         torch::Tensor scratch_storage,
         torch::Tensor raw_result_storage,
         torch::Tensor stats,
         torch::Tensor atom_mapping,
         torch::Tensor bond_mapping) {
  launch_fmcs_batch(tier_config,
                    pair_meta,
                    query_row_offsets,
                    query_col_indices,
                    query_bond_indices,
                    query_bond_endpoints,
                    target_row_offsets,
                    target_col_indices,
                    target_bond_indices,
                    target_bond_endpoints,
                    atom_match_words,
                    bond_match_words,
                    pair_input_storage,
                    queue_storage,
                    scratch_storage,
                    raw_result_storage,
                    stats,
                    atom_mapping,
                    bond_mapping);
}

PYBIND11_MODULE(TORCH_EXTENSION_NAME, module) {
  module.def("run", &run, "Optimized nvMolKit fMCS production batch");
}
